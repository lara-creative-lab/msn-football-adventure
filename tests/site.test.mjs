  assert.match(game, /prize\.type = "scarf"/);
  assert.match(game, /type: "matchball"/);
  assert.doesNotMatch(game, /彩虹奖励|红蘑菇|type: "rainbow"|type: "mushroom"/);
  assert.match(html, /500分＋3城梅西加入/);
  assert.match(html, /1000分＋6城苏亚雷斯加入/);
