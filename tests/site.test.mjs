  assert.doesNotMatch(html, /musicSelect|Dai Dai|火影|海贼王/);
  assert.match(html, /1000分＋6城苏亚雷斯加入并换巴萨战袍/);
  assert.match(game, /BARCA_CHARACTER_IMAGES/);
