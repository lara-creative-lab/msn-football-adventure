  assert.doesNotMatch(html, /北美三国|北美3国/);
  assert.match(html, /no-cache, no-store, must-revalidate/);
  assert.match(html, /game-v26\.js/);
  assert.match(html, /id="restartButton"[^>]*>重玩本关<\/button>/);
  assert.match(html, /id="firstLevelButton"[^>]*>从第1关开始<\/button>/);
  assert.doesNotMatch(html, /game\.js\?v=/);
  assert.doesNotMatch(html, /举办地|游艇|冰川|绿茵场|幻想森林层|晴海沙滩层|极光雪山层/);
  for (const city of ["罗马", "帕萨迪纳", "巴黎", "首尔", "横滨", "柏林", "开普敦", "里约", "莫斯科", "多哈", "墨西哥城", "多伦多", "旧金山"]) {
    assert.match(game, new RegExp(city));
  }
  assert.match(game, /drawRoundedRect\(18, 17, 560, 78/);
  assert.match(game, /关卡进度/);
  assert.match(game, /ctx\.textAlign = "center"; ctx\.textBaseline = "middle"/);
  assert.match(game, /trioBoxX \+ trioBoxW \/ 2/);
  assert.match(game, /trophyBoxX \+ trophyBoxW \/ 2/);
  assert.equal([...game.matchAll(/level\.scene ===/g)].length, 10);
  assert.equal([...game.matchAll(/routes: \{ main:/g)].length, 10);
  assert.doesNotMatch(game, /举办地历史街区|举办地城市广场|幻想森林层|晴海沙滩层|极光雪山层/);
