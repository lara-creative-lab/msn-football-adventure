  assert.match(game, /hat-adventure-city-stamps/);
  assert.match(game, /progressScore >= 1000 && stamps >= 6/);
  assert.match(game, /progressScore >= 500 && stamps >= 3/);
  assert.match(game, /function hasChampionsLeagueTrophy/);
